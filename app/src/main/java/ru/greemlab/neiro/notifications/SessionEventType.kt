package ru.greemlab.neiro.notifications

/**
 * Тип события по занятию для push-уведомления.
 */
enum class SessionEventType {
    /** Новая запись в расписании. */
    NEW_BOOKING,
    /** Отмена (статус «не пришёл» / отменён). */
    CANCELLED,
    /** Перенос: другая дата или время у того же клиента. */
    RESCHEDULED,
    /** Запись исчезла из календаря. */
    DELETED,
    /** Изменился статус (подтвердил, пришёл и т.д.). */
    STATUS_CHANGED,
    /** Напоминание за N минут до начала. */
    REMINDER,
    /** Сводка занятий на сегодня (один раз в день). */
    TODAY_DIGEST,
}
